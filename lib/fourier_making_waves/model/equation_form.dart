/// Equation forms shown above Discrete charts. PhET `EquationForm.ts`
enum EquationForm {
  /// Equations hidden; numeric tick labels.
  hidden,

  /// Mode form (n). Valid for all Domain values.
  mode,

  /// Domain.SPACE
  wavelength,
  spatialWaveNumber,

  /// Domain.TIME
  frequency,
  period,
  angularWaveNumber,

  /// Domain.SPACE_AND_TIME
  wavelengthAndPeriod,
  spatialAndAngular,
}
